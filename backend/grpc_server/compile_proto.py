"""
Utility script to compile Protocol Buffers contract (proto/defense.proto)
into Python stubs for both the gRPC Server and the API Gateway.
"""
import os
import sys
from pathlib import Path
from grpc_tools import protoc

def compile_protos():
    current_dir = Path(__file__).resolve().parent
    project_root = current_dir.parent.parent
    proto_dir = project_root / "proto"
    proto_file = proto_dir / "defense.proto"

    grpc_server_dir = project_root / "backend" / "grpc_server"
    gateway_dir = project_root / "backend" / "gateway"

    gateway_dir.mkdir(parents=True, exist_ok=True)
    grpc_server_dir.mkdir(parents=True, exist_ok=True)

    print(f"[*] Compiling proto file: {proto_file}")
    
    # Target directories to place generated code
    targets = [grpc_server_dir, gateway_dir]

    for target in targets:
        print(f"[*] Generating stubs in: {target}")
        protoc_args = [
            "protoc",
            f"-I{proto_dir}",
            f"--python_out={target}",
            f"--grpc_python_out={target}",
            str(proto_file)
        ]
        res = protoc.main(protoc_args)
        if res != 0:
            print(f"[!] Error compiling proto for {target}, exit code: {res}")
            sys.exit(res)
        
        # Ensure __init__.py exists in target folders
        init_file = target / "__init__.py"
        if not init_file.exists():
            init_file.write_text("# Autogenerated package marker\n", encoding="utf-8")
        
        # Check and fix import inside defense_pb2_grpc.py:
        # In proto3 generated grpc stubs, 'import defense_pb2 as defense__pb2' is used.
        # We ensure it can be imported both directly and as part of package.
        grpc_file = target / "defense_pb2_grpc.py"
        if grpc_file.exists():
            content = grpc_file.read_text(encoding="utf-8")
            if "import defense_pb2 as defense__pb2" in content:
                content = content.replace(
                    "import defense_pb2 as defense__pb2",
                    "try:\n    from . import defense_pb2 as defense__pb2\nexcept (ImportError, ValueError):\n    import defense_pb2 as defense__pb2"
                )
                grpc_file.write_text(content, encoding="utf-8")
                print(f"[+] Applied import patch to {grpc_file.name} in {target.name}")

    print("[SUCCESS] Protocol Buffers compiled successfully for Server and Gateway!")

if __name__ == "__main__":
    compile_protos()
